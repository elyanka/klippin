const LAND = (() => {
  const bin = atob(LAND_B64);
  const a = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) a[i] = bin.charCodeAt(i);
  return a;
})();

/** 1 when the cell containing (lon, lat) is land, else 0. */
export function landAt(lon, lat) {
  let x = Math.floor((lon + 180) / 360 * LAND_W);
  let y = Math.floor((90 - lat) / 180 * LAND_H);
  x = ((x % LAND_W) + LAND_W) % LAND_W;
  if (y < 0) y = 0;
  else if (y >= LAND_H) y = LAND_H - 1;
  const i = y * LAND_W + x;
  return (LAND[i >> 3] >> (7 - (i & 7))) & 1;
}

/** Land coverage of a cell plus its four neighbours, 0..1 — softens coasts. */
export function landSoft(lon, lat) {
  const d = 360 / LAND_W;
  return (landAt(lon, lat) * 4 + landAt(lon + d, lat) + landAt(lon - d, lat) +
          landAt(lon, lat + d) + landAt(lon, lat - d)) / 8;
}
